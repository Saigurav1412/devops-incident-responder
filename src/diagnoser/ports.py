"""The diagnoser's "ports": the things the graph needs from the outside world.

WHAT: small Protocol interfaces for (1) the LLM that reasons about the incident and (2) the
      executor that runs commands over A2A. (The health check is not a port: check_health builds
      one fixed curl command itself and sends it through the executor; see nodes.py.)
WHY:  the graph's control flow (replan loops, budget caps, the approval gate) is where most of
      the safety rules live, and it must be testable without an LLM, a VM or a network
      (AGENTS.md rules 1, 5 and 9). Keeping those dependencies behind interfaces means:
        * tests plug in scripted fakes (src/diagnoser/fakes.py) and run in milliseconds;
        * the real OpenAI-backed reasoner and the real A2A client can be swapped in later
          without touching graph.py or nodes.py.
HOW:  graph.build_graph() takes a DiagnoserDeps holding one implementation of each port.

Memory is the fourth dependency; its interface lives with its implementation in
src/memory/store.py because the memory slice owns it (INTERFACES §3).
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Protocol

from config import Settings
from contracts import (
    DiagnoseRequest,
    Hypothesis,
    IncidentState,
    Observation,
    RemediateRequest,
)
from memory.store import IncidentMemory

# ---------------------------------------------------------------------------------------------
# Reasoner: the LLM seam
# ---------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Reasoned[T]:
    """A reasoner answer plus the tokens it cost.

    WHY return tokens with every answer: MAX_TOKENS_PER_INCIDENT is enforced by the graph, in
    code (AGENTS.md rule 5). The graph can only enforce it if every LLM call reports its usage,
    so the interface makes reporting impossible to forget.
    """

    value: T
    tokens: int = 0  # total; what the token cap counts
    # Input/output split when the reasoner knows it (for cost); 0 = unknown.
    tokens_in: int = 0
    tokens_out: int = 0


@dataclass(frozen=True)
class FixProposal:
    """What the reasoner suggests doing. Deliberately has NO action_id.

    WHY: the action_id becomes the approval token's binding and the executor's idempotency key
    (INTERFACES §2.2, §4.3). It must be a fresh uuid generated by code, never a string an LLM
    chose (an LLM could repeat an old id and replay an earlier approval). nodes.propose_fix adds it.
    """

    action: str
    params: dict[str, str]
    rationale: str
    rollback: str | None = None


class ReasonerError(Exception):
    """The reasoner couldn't produce a usable answer (LLM unreachable, or output that stayed
    invalid after a repair attempt) for a step that has no safe default.

    Only `propose` raises it: plan / next_command / assess have safe defaults (empty plan ->
    escalate, no command, no status change). `tokens` carries what the failed attempts cost, so
    the budget still counts them.
    """

    def __init__(
        self, message: str, tokens: int = 0, tokens_in: int = 0, tokens_out: int = 0
    ) -> None:
        super().__init__(message)
        self.tokens = tokens
        self.tokens_in = tokens_in
        self.tokens_out = tokens_out


@dataclass(frozen=True)
class PolicySummaries:
    """The executor's policy in prompt-ready text, from its Agent Card skill descriptions
    (`diagnose`, `remediate`). Written by the executor from the config it enforces, so the prompt
    can't promise a command or fix the executor would refuse (Om's PR #12)."""

    diagnose: str
    remediate: str


class PolicySource(Protocol):
    """Where the reasoner gets PolicySummaries. A2AExecutorClient implements it from the card."""

    async def policy_summaries(self) -> PolicySummaries: ...


class Reasoner(Protocol):
    """Everything the graph asks the LLM. Each method sees the whole IncidentState.

    The real implementation must treat `state["observations"]` and `state["recalled"]` as
    untrusted data (AGENTS.md rule 2): command output and log lines are attacker-controlled.
    """

    async def plan(self, state: IncidentState) -> Reasoned[list[Hypothesis]]:
        """Propose hypotheses for the alert. On a replan, prior refuted ones are in the state."""
        ...

    async def next_command(self, state: IncidentState) -> Reasoned[list[str] | None]:
        """Pick one read-only diagnostic argv to run next, or None if there's nothing useful left."""
        ...

    async def assess(self, state: IncidentState) -> Reasoned[list[Hypothesis]]:
        """Re-score the hypotheses against the observations (open / confirmed / refuted)."""
        ...

    async def propose(self, state: IncidentState) -> Reasoned[FixProposal]:
        """Choose one remediation-catalog action for the confirmed hypothesis."""
        ...


# ---------------------------------------------------------------------------------------------
# Executor client: the A2A seam
# ---------------------------------------------------------------------------------------------


class ExecutorClientError(Exception):
    """The executor couldn't be reached or answered with something unparseable.

    This is a *transport* failure (network down, bad Agent Card, malformed Task). It is different
    from TASK_STATE_REJECTED / TASK_STATE_FAILED, which are normal answers and come back as an
    Observation. The diagnose/execute nodes catch this and record it as a failed Observation, so
    one network blip becomes evidence for the reasoner instead of crashing the incident.
    """


class ExecutorClient(Protocol):
    """One A2A SendMessage per call (INTERFACES §2.2). Returns the executor's answer as an
    Observation, whatever the task state; raises ExecutorClientError only on transport failure."""

    async def diagnose(self, request: DiagnoseRequest) -> Observation: ...

    async def remediate(self, request: RemediateRequest) -> Observation: ...


# ---------------------------------------------------------------------------------------------
# Bundle passed to build_graph
# ---------------------------------------------------------------------------------------------


@dataclass
class DiagnoserDeps:
    """Everything the nodes need. One object, so node signatures stay `(state) -> update`."""

    reasoner: Reasoner
    executor: ExecutorClient
    memory: IncidentMemory
    settings: Settings
    # Injectable clock: tests move time forward to trigger the wall-clock cap deterministically.
    clock: Callable[[], datetime] = field(default=lambda: datetime.now(UTC))
